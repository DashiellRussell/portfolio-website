// Packs the 3D models for the site so they are never served as plain .glb
// files. Runs before `dev` and `build`.
//
// The source models live in assets/models (outside public/, so Next never
// serves them). Each build encrypts every model with AES-256-GCM under a fresh
// random key and writes it to public/_m/<random>.bin; the key, IV and URL go
// into components/3d/models.generated.ts, which the bench imports. Both
// outputs are gitignored and change on every build, so a saved URL or file
// stops working at the next deploy.
//
// This is deterrence, not DRM: the browser has to decrypt a model to draw it,
// so the key necessarily ships in the page's JavaScript. It stops right-click
// saving, the network tab, "download all assets" tools and hotlinking (proxy.ts
// refuses /_m/ requests that are not the site's own fetches), but not someone
// willing to dig through the bundle or capture GPU buffers.
import { createCipheriv, randomBytes } from "node:crypto"
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const MODELS = {
  arm: "cyra-arm.glb",
  winder: "stator-winder.glb",
}

const root = process.cwd()
const outDir = join(root, "public", "_m")
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const key = randomBytes(32)
const entries = {}
for (const [name, file] of Object.entries(MODELS)) {
  const plain = readFileSync(join(root, "assets", "models", file))
  const iv = randomBytes(12)
  const cipher = createCipheriv("aes-256-gcm", key, iv)
  // WebCrypto expects the 16-byte tag appended to the ciphertext
  const sealed = Buffer.concat([cipher.update(plain), cipher.final(), cipher.getAuthTag()])
  const id = randomBytes(12).toString("hex")
  writeFileSync(join(outDir, `${id}.bin`), sealed)
  entries[name] = { url: `/_m/${id}.bin`, iv: iv.toString("base64") }
}

const src = `// Generated by scripts/pack-models.mjs on every dev/build run. Do not edit or commit.
export const MODEL_KEY = ${JSON.stringify(key.toString("base64"))}
export const MODELS = ${JSON.stringify(entries, null, 2)} as const
`
writeFileSync(join(root, "components", "3d", "models.generated.ts"), src)
console.log(`[models] packed ${Object.keys(entries).length} models into public/_m`)
